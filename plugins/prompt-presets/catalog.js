function category(id, name, lines) {
  return { id, name, prompts: lines.map(([title, body], index) => ({ id: `${id}-${index + 1}`, title, body })) }
}

function library(categories, picks) {
  return { categories, featured: picks.map(([group, row]) => categories[group].prompts[row].id) }
}

