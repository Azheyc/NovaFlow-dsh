/** Generate NovaFlow desktop, installer and shared UI artwork from the supplied mark. */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import sharp from 'sharp'
import { packIco, renderTrayIconEntries } from './render-tray-icon.ts'
import { renderNovaFlowAnimation } from './render-novaflow-animation.ts'

const root = new URL('../../../', import.meta.url)
const write = async (path: string, data: string | Buffer): Promise<void> => writeFile(new URL(path, root), data)
const mark = await readFile(new URL('apps/desktop/resources/novaflow/mark.svg', root), 'utf8')
const sourcePath = /<path d="([^"]+)"/u.exec(mark)?.[1]
if (sourcePath === undefined) throw new Error('NovaFlow artwork requires a path')
const wordmark = await readFile(new URL('apps/desktop/resources/novaflow/wordmark.svg', root), 'utf8')
const wordmarkPath = /<path d="([^"]+)"/u.exec(wordmark)?.[1]
if (wordmarkPath === undefined) throw new Error('NovaFlow wordmark requires a path')
// Trim excess source margins without changing the three sails' relative geometry.
const path = sourcePath.replace(/([ML])(\d+) (\d+)/gu, (_match: string, command: string, x: string, y: string) =>
  `${command}${((Number(x) - 511) * 1.2 + 512).toFixed(1)} ${((Number(y) - 519) * 1.2 + 512).toFixed(1)}`)
const glyph = `<path d="${path}" fill="#fff"/>`
const tile = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><rect width="1024" height="1024" rx="160" fill="#000"/><g id="tray-glyph"><g id="brand-glyph">${glyph}</g></g></svg>\n`
for (const name of ['icon', 'icon-windows', 'icon-macos']) {
  await write(`apps/desktop/resources/${name}.svg`, tile)
  await write(`apps/desktop/resources/${name}.png`, await sharp(Buffer.from(tile)).png({ compressionLevel: 9 }).toBuffer())
}
await write('apps/desktop/resources/tray-windows.ico', packIco(await renderTrayIconEntries(Buffer.from(tile))))
for (const target of [
  'apps/desktop/renderer/assets/novaflow.svg',
  'apps/desktop/renderer/assets/welcome-brand.svg',
  'apps/novaflow-plugin/icon.svg',
  'apps/web/public/favicon.svg',
  'apps/web/public/favicon-dark.svg',
  'website/public/favicon.svg',
]) await write(target, tile)
await write('packages/client/ui-primitives/src/brand-artwork.ts',
  `/** NovaFlow artwork generated by apps/desktop/scripts/render-novaflow-brand.ts. */\nexport const NOVAFLOW_LOGO_PATH = '${path}'\n\n/** NovaFlow lettering outlined from Montserrat Medium (SIL Open Font License). */\nexport const NOVAFLOW_WORDMARK_PATH = '${wordmarkPath}'\n`)
execFileSync(process.execPath, ['--import', 'tsx/esm', fileURLToPath(new URL('apps/web/scripts/render-app-icons.ts', root))],
  { cwd: fileURLToPath(root), stdio: 'inherit' })
for (const dark of [false, true]) {
  for (const scale of [1, 2]) {
    const header = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="196" viewBox="0 0 600 196"><svg x="48" y="48" width="100" height="100" viewBox="0 0 1024 1024"><rect width="1024" height="1024" rx="160" fill="#000"/>${glyph}</svg><svg x="176" y="54" width="322" height="88" viewBox="0 0 88 24"><path d="${wordmarkPath}" fill="${dark ? '#fff' : '#000'}"/></svg></svg>`
    const name = `brand${dark ? '-dark' : ''}${scale === 2 ? '-2x' : ''}.png`
    await write(`apps/desktop/installer/assets/${name}`, await sharp(Buffer.from(header)).resize(600 * scale, 196 * scale).png({ compressionLevel: 9 }).toBuffer())
  }
}
const sidebar = `<svg xmlns="http://www.w3.org/2000/svg" width="164" height="314"><rect width="164" height="314" fill="#000"/><svg x="18" y="80" width="128" height="128" viewBox="0 0 1024 1024">${glyph}</svg><svg x="26" y="215" width="112" height="31" viewBox="0 0 88 24"><path d="${wordmarkPath}" fill="#fff"/></svg></svg>`
await write('apps/desktop/installer/assets/uninstaller-sidebar.png', await sharp(Buffer.from(sidebar)).png({ compressionLevel: 9 }).toBuffer())
console.info(`NovaFlow artwork generated from ${fileURLToPath(new URL('apps/desktop/resources/novaflow/mark.svg', root))}`)
await renderNovaFlowAnimation()
